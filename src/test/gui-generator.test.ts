test("spec carries the palette, mode and structure for auditing", () => {
  const result = generateGui({ description: "main menu", palette: "candy-pop", mode: "light" });
  assert.equal(result.spec.paletteId, "candy-pop");
  assert.equal(result.spec.mode, "light");
  assert.equal(result.spec.fullscreen, true);
  assert.ok(result.spec.children.length > 0);
  assert.ok(result.notes.length >= 4);
});

test("emitted Luau is StyLua-canonical (structural invariants)", () => {
  const kinds2: GuiKind[] = ["shop", "settings", "hud"];
  for (const kind of kinds2) {
    const { luau } = generateGui({ description: kind, kind });
    // No multi-property lines inside table constructors.
    const multiProp = luau.split("\n").filter((l) => /^[\t ]+[A-Za-z_][\w.]*\s*=\s.*,\s+[A-Z][A-Za-z0-9_]*\s*=\s/.test(l));
    assert.deepEqual(multiProp, [], `${kind}: multi-prop lines remain`);
    // The depth-aware canonicalizer is idempotent on its own output.
    assert.equal(finalizeLuau(luau), luau, `${kind}: output not canonical`);
    // No triple blank lines.
    assert.ok(!luau.includes("\n\n\n"), `${kind}: blank line runs remain`);
    // Lines fit the shipped column width (comments excluded — banners are wide).
    const longLines = luau.split("\n").filter((l) => !l.trimStart().startsWith("--") && l.length > 130);
    assert.deepEqual(longLines, [], `${kind}: lines exceed 130 columns`);
  }
});
