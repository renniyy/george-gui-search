/**
 * GEORGE GUI @Search — shared Luau shell emitted into every generated module.
 *
 * The shell provides: theme tokens, instance factory, tween helper, button
 * interaction hook (hover / press / gamepad focus), the action dispatcher,
 * and the public controller API (mount / open / close / toggle / on / unmount).
 */

import { DesignSystem, emitThemeModuleTokens, luauColor3, resolveSide, SCALES } from "./tokens.js";

export interface ShellContext {
  guiName: string;
  kindLabel: string;
  ds: DesignSystem;
  version: string;
}

export function prelude(ctx: ShellContext): string {
  const themeTable = emitThemeModuleTokens(ctx.ds, ctx.guiName);
  return `--!strict
-- ════════════════════════════════════════════════════════════════════════
--  ${ctx.guiName} · ${ctx.kindLabel}
--  Generated by GEORGE GUI @Search v${ctx.version}
--  Design system: ${ctx.ds.palette.name} (${ctx.ds.mode})
--  Build beyond imagination.
--
--  Drop this ModuleScript into ReplicatedStorage (or wherever you keep UI),
--  then from a LocalScript:
--      local UI = require(path.to.${ctx.guiName})
--      local ui = UI.mount()
--      ui:open()
--      ui:on("<action>", function(payload) ... end)
-- ════════════════════════════════════════════════════════════════════════

local Players = game:GetService("Players")
local TweenService = game:GetService("TweenService")
local UserInputService = game:GetService("UserInputService")

${themeTable}

-- ── Helpers ──────────────────────────────────────────────────────────────

local function create(className: string, props: { [string]: any }, parent: Instance?): any
	local instance = Instance.new(className)
	for key, value in props do
		instance[key] = value
	end
	if parent ~= nil then
		instance.Parent = parent
	end
	return instance
end

local function withTween(
	instance: Instance,
	goal: { [string]: any },
	duration: number?,
	style: Enum.EasingStyle?,
	direction: Enum.EasingDirection?
): Tween
	local info =
		TweenInfo.new(duration or Theme.Motion.base, style or Enum.EasingStyle.Quint, direction or Enum.EasingDirection.Out)
	local tween = TweenService:Create(instance, info, goal)
	tween:Play()
	return tween
end

-- Attaches hover / press / gamepad-focus feedback and dispatches the action.
local function hookButton(button: TextButton, actionName: string, fire: (string, any) -> (), payload: any?)
	local scale = create("UIScale", { Scale = 1 }, button)
	button.AutoButtonColor = false
	button.MouseEnter:Connect(function()
		withTween(scale, { Scale = 1.04 }, Theme.Motion.fast)
	end)
	button.MouseLeave:Connect(function()
		withTween(scale, { Scale = 1 }, Theme.Motion.fast)
	end)
	button.SelectionGained:Connect(function()
		withTween(scale, { Scale = 1.05 }, Theme.Motion.fast)
	end)
	button.SelectionLost:Connect(function()
		withTween(scale, { Scale = 1 }, Theme.Motion.fast)
	end)
	button.Activated:Connect(function()
		withTween(scale, { Scale = 0.96 }, Theme.Motion.fast, Enum.EasingStyle.Quint, Enum.EasingDirection.In)
		task.delay(Theme.Motion.fast, function()
			withTween(scale, { Scale = 1 }, Theme.Motion.fast)
		end)
		fire(actionName, if payload ~= nil then payload else button)
	end)
	return button
end
`;
}

/** Mount wrapper + controller API that surrounds each kind's build body. */
export function shell(
  ctx: ShellContext,
  usageNote: string,
  buildBody: string,
  controllerExtras: string,
  openTween: string,
  closeTween: string
): string {
  return `${prelude(ctx)}
-- ── Module ───────────────────────────────────────────────────────────────
${usageNote}

local UI = {}
UI.Version = "${ctx.version}"

local mounted: any = nil

function UI.mount(parent: Instance?): any
	if mounted ~= nil then
		mounted.unmount()
	end

	local playerGui: Instance = parent or Players.LocalPlayer:WaitForChild("PlayerGui")
	local fire: (string, any) -> ()
	local actions: { [string]: { (any) -> () } } = {}
	local buttons: { [string]: TextButton } = {}
	local widgets: { [string]: Instance } = {}
	local state = { open = false }

	fire = function(actionName: string, payload: any)
		local callbacks = actions[actionName]
		if callbacks ~= nil then
			for _, callback in callbacks do
				task.spawn(callback, payload)
			end
		end
	end

	local screen = create("ScreenGui", {
		Name = "${ctx.guiName}",
		ResetOnSpawn = false,
		IgnoreGuiInset = true,
		ZIndexBehavior = Enum.ZIndexBehavior.Sibling,
		DisplayOrder = 10,
		Enabled = true,
	}, playerGui)

${buildBody}

	local controller = {}
	controller.screen = screen
	controller.buttons = buttons
	controller.widgets = widgets
	controller.isOpen = function(): boolean
		return state.open
	end

	function controller.on(actionName: string, callback: (any) -> ())
		local list = actions[actionName]
		if list == nil then
			list = {}
			actions[actionName] = list
		end
		table.insert(list, callback)
		return controller
	end

${controllerExtras}

	function controller.open()
		if state.open then
			return
		end
		state.open = true
		screen.Enabled = true
${openTween}
	end

	function controller.close()
		if not state.open then
			return
		end
		state.open = false
${closeTween}
		task.delay(Theme.Motion.slow + 0.05, function()
			if not state.open then
				screen.Enabled = false
			end
		end)
	end

	function controller.toggle()
		if state.open then
			controller.close()
		else
			controller.open()
		end
	end

	function controller.unmount()
		screen:Destroy()
		mounted = nil
	end

	mounted = controller
	return controller
end

return UI
`;
}

