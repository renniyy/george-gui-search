/**
 * GEORGE GUI @Search — project scaffolder ("George Architect").
 *
 * Emits a complete Rojo-compatible project: source tree, toolchain pins
 * (Rokit), package manifest (Wally), lint/format configs and a README.
 * The scaffold is what turns generated modules into a real repository.
 */

import { finalizeLuau } from "./luau-text.js";

export interface ScaffoldResult {
  name: string;
  tree: string;
  files: Array<{ path: string; content: string }>;
}

function sanitize(name: string): string {
  const clean = name.replace(/[^a-zA-Z0-9-_ ]/g, " ").replace(/\s+/g, " ").trim();
  if (!clean) return "MyRobloxGame";
  return clean;
}

export function scaffoldProject(rawName: string): ScaffoldResult {
  const name = sanitize(rawName);
  const files: Array<{ path: string; content: string }> = [];


  files.push({
    path: "default.project.json",
    content: JSON.stringify(
      {
        name,
        tree: {
          $className: "DataModel",
          ReplicatedStorage: {
            $className: "ReplicatedStorage",
            Shared: { $path: "src/shared" },
            Packages: { $path: "Packages" },
          },
          ServerScriptService: {
            $className: "ServerScriptService",
            Server: { $path: "src/server" },
          },
          StarterPlayer: {
            $className: "StarterPlayer",
            StarterPlayerScripts: {
              $className: "StarterPlayerScripts",
              Client: { $path: "src/client" },
            },
          },
          Workspace: { $className: "Workspace" },
        },
      },
      null,
      2
    ) + "\n",
  });

  files.push({
    path: "rokit.toml",
    content: `# Pinned toolchain — every contributor and CI runner gets identical tools.
[tools]
rojo = "rojo-rbx/rojo@7.4.4"
stylua = "JohnnyMorganz/StyLua@2.0.2"
wally = "UpliftGames/wally@0.3.2"
luau-lsp = "JohnnyMorganz/luau-lsp@1.38.1"
`,
  });

  files.push({
    path: "wally.toml",
    content: `[package]
name = "${name.toLowerCase().replace(/[^a-z0-9-]/g, "-")}/game"
version = "0.1.0"
registry = "https://github.com/UpliftGames/wally-index"
realm = "shared"

[dependencies]
`,
  });

  files.push({
    path: "stylua.toml",
    content: `column_width = 130
line_endings = "Unix"
indent_type = "Tabs"
quote_style = "AutoPreferDouble"
`,
  });

  files.push({
    path: "selene.toml",
    content: `std = "roblox+lune"

[lints]
high_cyclomatic_complexity = "warn"
`,
  });

  files.push({
    path: "src/server/init.server.lua",
    content: `--!strict
-- Server entry point. Generated by GEORGE GUI @Search.
local ServerScriptService = game:GetService("ServerScriptService")

print("[${name}] server bootstrap ready")
`,
  });

  files.push({
    path: "src/client/init.client.lua",
    content: `--!strict
-- Client entry point. Generated by GEORGE GUI @Search.
-- Mount generated UI modules here, e.g.:
--   local MainMenuUI = require(game.ReplicatedStorage.Shared.MainMenuUI)
--   local ui = MainMenuUI.mount()
--   ui:open()
local ReplicatedStorage = game:GetService("ReplicatedStorage")

local Shared = ReplicatedStorage:WaitForChild("Shared")
print("[${name}] client bootstrap ready")
`,
  });

  files.push({
    path: "src/shared/init.lua",
    content: `--!strict
-- Shared modules: generated UI controllers, Net layer and utilities live here.
return {}
`,
  });

  files.push({
    path: ".gitignore",
    content: `Packages/
sourcemap.json
*.rbxlx.lock
.DS_Store
`,
  });

  files.push({
    path: "README.md",
    content: `# ${name}

Roblox project scaffolded by GEORGE GUI @Search.

## Workflow

1. Install tools with [Rokit](https://github.com/rojo-rbx/rokit): \`rokit install\`
2. Open the project in Studio: \`rojo serve\` + the Rojo plugin, or build with \`rojo build -o game.rbxlx\`
3. Format with \`stylua .\` and lint with \`selene .\`
4. Add packages with \`wally install\`

Generated UI modules (from the george_generate_gui tool) belong in \`src/shared/\`.
`,
  });

  const tree = [
    `${name}/`,
    `├── default.project.json`,
    `├── rokit.toml`,
    `├── wally.toml`,
    `├── stylua.toml`,
    `├── selene.toml`,
    `├── .gitignore`,
    `├── README.md`,
    `├── src/`,
    `│   ├── server/init.server.lua`,
    `│   ├── client/init.client.lua`,
    `│   └── shared/init.lua`,
    `└── Packages/            (wally output, gitignored)`,
  ].join("\n");

  return { name, tree, files: files.map((f) => ({ ...f, content: finalizeLuau(f.content) })) };
}
